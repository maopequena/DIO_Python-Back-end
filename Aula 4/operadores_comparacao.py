saldo = 200
saque = 200

print(saldo == saque)          # Igualdade
print(saldo != saque)          # Diferença
print(saldo > saque)           # Maior que
print(saldo < saque)           # Menor que
print(saldo >= saque)          # Maior ou igual a
print(saldo <= saque)          # Menor ou igual a
print("\n")
